    fun makeConversational(persianText: String): String {
        var text = persianText.trim()
        if (text.isEmpty()) return text

        for ((target, replacement) in rules) {
            text = text.replace(target, replacement)
        }

        // پاکسازی نویزهای کلمات انگلیسی به جا مانده از OCR در ترجمه فارسی
        text = text.replace(Regex("\\bSOI\\b", RegexOption.IGNORE_CASE), "")
            .replace(" این IS ", " این ")
            .replace(" این IS", " این")
            .replace(" IS ", " ")
            .replace(Regex("\\s+"), " ")
            .trim()

        return text
    }
